}

# A cron line naming planwright, claude, or a path of the program's is a
# hand-built watcher until the operator says which duty, if any, it serves.
doctor_cron() {
  command -v crontab >/dev/null 2>&1 || return 0
  dc_tab=$(crontab -l 2>/dev/null) || return 0
  dc_home=''
  if ! dc_paths=$(/bin/bash "$script_dir/mc-program.sh" get "$1" repositories 2>/dev/null) \
    || ! dc_home=$(/bin/bash "$script_dir/mc-program.sh" get "$1" home 2>/dev/null); then
    printf 'unknown\tcron\tthe program repositories or home could not be read, so lines naming them are not listed\n'
  fi
  # Every NAME=value is blanked: a crontab line is where credentials sit,
  # and a reported line travels into items and the program home. Control
  # bytes go first, so none can hide an assignment the scan would miss;
  # a value is one shell word, quotes and escapes included, and a quote left
  # open blanks the rest of the line.
  printf '%s\n' "$dc_tab" | mc_clean_text | DC_PATHS="$dc_paths${nl}$dc_home" DC_Q="'" awk '
    BEGIN {
      n = split(ENVIRON["DC_PATHS"], needle, "\n")
      sq = ENVIRON["DC_Q"]
      dq = "\""
    }
    function value_end(s, i, enc,   len, c, q, d) {
      len = length(s)
      q = enc
      d = 0
      for (; i <= len; i++) {
        c = substr(s, i, 1)
        if (q == sq) {
          if (c == sq) { if (enc == sq) return i; q = "" }
        } else if (q == dq) {
          if (c == "\\") i++
          else if (c == dq) { if (enc == dq) return i; q = "" }
        } else if (c == "\\") i++
        else if (c == sq || c == dq) q = c
        else if (c == "(") d++
        else if (c == ")" && d > 0) d--
        else if (c == " " && d == 0) return i
      }
      return len + 1
    }
    function redact(s,   out, len, i, c, q, k) {
      # An environment line (crontab(5): blanks may sit around the =, and
      # the value runs to the end of the line) is one assignment.
      if (s ~ /^ *[^ 0-9*@][^=]*=/) {
        k = substr(s, 1, index(s, "=") - 1)
        gsub(/^ +| +$/, "", k)
        return k "=<redacted>"
      }
      out = ""
      q = ""
      len = length(s)
      for (i = 1; i <= len; i++) {
        c = substr(s, i, 1)
        if (c ~ /[A-Za-z_]/ && (i == 1 || substr(s, i - 1, 1) !~ /[A-Za-z0-9_]/) \
          && match(substr(s, i), /^[A-Za-z_][A-Za-z0-9_]*=/)) {
          k = RLENGTH
          out = out substr(s, i, k) "<redacted>"
          i = value_end(s, i + k, q) - 1
          continue
        }
        if (c == "\\" && q != sq) {
          out = out c
          i++
          c = substr(s, i, 1)
        } else if (q == "" && (c == sq || c == dq)) q = c
        else if (c == q) q = ""
        out = out c
      }
      return out
    }
    { gsub(/\t/, " ") }
    /^ *(#|$)/ { next }
    # The two names match in any case (PLANWRIGHT_ROOT=, Claude-sweep.sh);
    # a path matches only as spelled, as the filesystem reads it.
    index(tolower($0), "planwright") || index(tolower($0), "claude") { print "cron\t" redact($0); next }
    { for (i = 1; i <= n; i++) if (needle[i] != "" && index($0, needle[i])) { print "cron\t" redact($0); next } }'
}

v_doctor() {
  [ $# -eq 2 ] && [ "$1" = --program ] || usage
  mc_require_program "$2"
  dr_out=$(
    doctor_overrides
    doctor_duties "$2"
    doctor_launches "$2"
    doctor_cron "$2"
  )
  if [ -n "$dr_out" ]; then
    printf '%s\n' "$dr_out" | mc_clean_text
  else
    printf 'clean\n'
  fi
}


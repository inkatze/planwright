  check_value "$2"
  value_ok "$1" "$2" || mc_usage_fail "$2 is not a value of $1"
  layer_path
  lock_layer
  VALIDATE='' write_keys "$1" "$2"
}

v_restore() {
  [ $# -eq 1 ] || [ $# -eq 2 ] || usage
  rs_v=${2:-}
  [ -z "$rs_v" ] || check_value "$rs_v"
  VALIDATE=''
  if [ "$1" = mission_control_programs ]; then
    [ -z "$rs_v" ] || valid_program_list "$rs_v" || mc_usage_fail "mission_control_programs is a [..] list of program names"
  elif program_key "$1"; then
    VALIDATE=$PK_PROGRAM
  elif knob_writable "$1"; then
    [ -z "$rs_v" ] || value_ok "$1" "$rs_v" || mc_usage_fail "$rs_v is not a value of $1"
  else
    mc_usage_fail "$(sanitize_printable "$1") is not a key mission control writes"
  fi
  layer_path
  lock_layer
  write_keys "$1" "$rs_v"
}

v_apply() {
  [ $# -ge 3 ] && [ "$1" = --program ] || usage
  ap_p=$2 ap_id=$3
  shift 3
  ap_value=''
  if [ $# -gt 0 ]; then
    [ $# -eq 2 ] && [ "$1" = --value ] || usage
    ap_value=$2
    check_value "$ap_value"
  fi
  case $ap_id in
    p-[1-9] | p-[1-9]*[0-9]) mc_valid_uint "${ap_id#p-}" || mc_usage_fail "a proposal id is p-<n>" ;;
    *) mc_usage_fail "a proposal id is p-<n>" ;;
  esac
  mc_require_program "$ap_p"
  ap_home=$(mc_program_home "$ap_p")
  ap_store=$ap_home/kb/proposals.tsv
  if [ ! -f "$ap_store" ] || [ -L "$ap_store" ] || ! mc_store_ok "$ap_store"; then
    mc_fail "store kb/proposals.tsv is missing or has a missing or unknown format"
  fi
  ap_row=$(I=$ap_id awk -F '\t' '$1 == ENVIRON["I"] && NF >= 17 { print; exit }' "$ap_store")
  [ -n "$ap_row" ] || mc_fail "no proposal $ap_id"
  ap_col() { printf '%s\n' "$ap_row" | cut -f "$1"; }
  ap_state=$(ap_col 17) ap_kind=$(ap_col 8) ap_mech=$(ap_col 9) ap_where=$(ap_col 10)
  ap_change=$(ap_col 12) ap_subject=$(ap_col 5)
  [ "$ap_state" = accepted ] || mc_fail "proposal $ap_id is $(sanitize_printable "$ap_state"), not accepted"

  ap_key='' ap_write=''
  case $ap_kind in
    rule) mc_fail "a rule proposal is applied when it is accepted (mc-proposals.sh accept)" ;;
    duty)
      [ -z "$ap_value" ] || mc_usage_fail "a duty proposal takes no --value"
      mc_valid_kebab "$ap_mech" || mc_fail "proposal $ap_id names no duty id"
      ap_key=$(pkey "$ap_p" duties) ap_write=duty
      ;;
    knob)
      # A denial's knob sets a guard's posture, the operator's even when the
      # key is one this script writes.
      if [ "$(ap_col 4)" = denial ]; then
        :
      elif program_key "$ap_mech" && [ "$PK_PROGRAM" = "$ap_p" ]; then
        ap_key=$ap_mech ap_write=program
      elif knob_writable "$ap_mech"; then
        ap_key=$ap_mech ap_write=knob
      fi
      if [ -n "$ap_write" ]; then
        [ -n "$ap_value" ] || mc_usage_fail "a knob proposal needs the --value the operator accepted"
        value_ok "$ap_key" "$ap_value" || mc_usage_fail "$ap_value is not a value of $ap_key"
      fi
      ;;
    catalog-step)
      printf 'dispatch\t%s\t%s\n' "$ap_where" "$ap_change" | mc_clean_text
      return 0
      ;;
  esac
  if [ -z "$ap_write" ]; then
    printf 'handover-operator\t%s\t%s\n' "$ap_where" "$ap_change" | mc_clean_text
    return 0
  fi

  layer_path
  lock_layer
  mc_kb_lock "$ap_p" config-apply
  # The reversal this apply would log, then the live undo entry: this
  # proposal's config-set entry with that same reversal that no revert
  # (reverting, reverted or revert failed) has since named. An entry whose
  # reversal differs restores a value since replaced, so it is not reused.
  if [ "$ap_write" = duty ]; then
    ap_rev_args=(mc-config.sh duty --program "$ap_p" disable "$ap_mech")
  else
    ap_prev=$(previous "$ap_key")
    if [ "$ap_prev" = - ]; then
      ap_rev_args=(mc-config.sh restore "$ap_key")
    else
      ap_rev_args=(mc-config.sh restore "$ap_key" "$ap_prev")
    fi
  fi
  ap_rev=argv:
  ap_sep=''
  for ap_w in "${ap_rev_args[@]}"; do
    ap_w=${ap_w//%/%25}
    ap_rev=$ap_rev$ap_sep${ap_w// /%20}
    ap_sep=' '
  done
  ap_undo=$(mc_kb query undo --program "$ap_p" --subject "$ap_subject") || mc_fail "the undo log cannot be read"
  ap_logged=$(printf '%s\n' "$ap_undo" | I=$ap_id R=$ap_rev awk -F '\t' '
    $4 == "config-set" && $7 == ENVIRON["R"] && index($6, ": applied accepted mechanization proposal " ENVIRON["I"]) && substr($6, length($6) - length(ENVIRON["I"]) + 1) == ENVIRON["I"] { live[$1] = 1; order[++n] = $1 }
    $4 == "reverting" || $4 == "reverted" || $4 == "revert failed" { delete live[$5] }
    END { for (i = n; i > 0; i--) if (order[i] in live) { print order[i]; exit } }')
  if [ "$ap_write" = duty ]; then
    duty_list "$ap_p" enable "$ap_mech"
    ap_value=$DUTY_LIST
    ap_done=''
    [ -n "$DUTY_CHANGED" ] || ap_done=1
  else
    ap_done=''
    [ "$(cfg_get "$ap_key" 2>/dev/null)" != "$ap_value" ] || ap_done=1
  fi
  if [ -n "$ap_done" ]; then
    printf 'applied\talready\t%s\n' "$ap_id"
    return 0
  fi
  VALIDATE=''
  [ "$ap_write" = knob ] || VALIDATE=$ap_p
  prepare "$ap_key" "$ap_value"
  handover_if_managed
  if [ -z "$ap_logged" ]; then
    ap_rules=$(/bin/bash "$script_dir/mc-rules.sh" active "$ap_p") || mc_fail "the rule store cannot be read"
    # shellcheck disable=SC2016 # an awk program, expanded by awk
    ap_cite=$(printf '%s\n' "$ap_rules" | S=$ap_subject awk -F '\t' "$MC_SUBJECT_KEY_AWK"'
      $1 ~ /^r-[1-9][0-9]*$/ && key($5) == key(ENVIRON["S"]) { c = c (c == "" ? "" : ",") $1 }
      END { print (c == "" ? "-" : c) }')
    ap_out=$(mc_kb append undo --program "$ap_p" --subject "$ap_subject" --act config-set --target "$ap_key" \
      --grounds "settled - $ap_cite: applied accepted mechanization proposal $ap_id" -- "${ap_rev_args[@]}") \
      || mc_fail "the undo entry was not logged, so proposal $ap_id was not applied"
    ap_logged=$(printf '%s\n' "$ap_out" | head -n 1)
  fi
  land >/dev/null
  printf 'applied\t%s\t%s\t%s\t%s\n' "$ap_kind" "$ap_key" "$ap_value" "$ap_logged" | mc_clean_text
}

doctor_overrides() {
  do_defaults="$script_dir/../config/defaults.yml"
  do_keys=$(awk -F: '/^mission_control_[a-z0-9_]*:/ && $1 != "mission_control_programs" { print $1 }' "$do_defaults" 2>/dev/null)
  [ -n "$do_keys" ] || {
    printf 'unknown\toverrides\tthe shipped defaults could not be read\n'
    return 0
  }
  # A plain read skips a malformed adopter or machine-local layer with only a
  # stderr warning, which would print clean; the strict read names it.
  # shellcheck disable=SC2086 # one key per word, by design
  do_lines=$(PLANWRIGHT_CONFIG_STRICT_OVERLAYS=1 /bin/sh "$script_dir/config-get.sh" --layers $do_keys 2>/dev/null)
  case $? in
    0) ;;
    6)
      printf 'unknown\toverrides\tan adopter or machine-local layer is malformed or unreadable, so what it sets is not listed\n'
      # shellcheck disable=SC2086 # one key per word, by design
      do_lines=$(cfg_get --layers $do_keys 2>/dev/null) || return 0
      ;;
    *)
      printf 'unknown\toverrides\tthe layers could not be read\n'
      return 0
      ;;
  esac
  printf '%s\n' "$do_lines" | awk -F '\t' '
    NF < 3 { next }
    !($1 in last) { keys[++n] = $1 }
    $2 == "core" { core[$1] = $3 }
    { layer[$1] = $2; last[$1] = $3 }
    END {
      for (i = 1; i <= n; i++) {
        k = keys[i]
        if (layer[k] != "core" && (k in core) && last[k] != core[k])
          print "override\t" k "\t" layer[k] "\t" last[k] "\t" core[k]
      }
    }'
}

doctor_duties() {
  if ! dd_on=$(/bin/bash "$script_dir/mc-program.sh" get "$1" duties 2>/dev/null) \
    || ! dd_default=$(/bin/bash "$script_dir/mc-program.sh" default duties 2>/dev/null); then
    printf 'unknown\tduties\tthe enabled or default duties could not be read\n'
    return 0
  fi
  printf '%s\n' "$dd_default" | while IFS= read -r dd_id; do
    [ -n "$dd_id" ] || continue
    printf '%s\n' "$dd_on" | grep -qxF -- "$dd_id" || printf 'duty-off\t%s\n' "$dd_id"
  done
}


# --- brief.md: prose sections, kill criteria, tracks, sources, gate log ---

file == "brief.md" && isprose(sect) {
  if ($0 ~ /^[ \t]*$/) { PBREAK[sect] = 1; next }
  line = trim($0)
  if (PROSE[sect] == "") PROSE[sect] = line
  else if (PBREAK[sect] || line ~ /^- /) PROSE[sect] = PROSE[sect] "\n" line
  else PROSE[sect] = PROSE[sect] " " line
  PBREAK[sect] = 0
  next
}

file == "brief.md" && sect == "Kill criteria" && /^\*\*Gate decider:\*\*/ {
  d = $0; sub(/^\*\*Gate decider:\*\*[ \t]*/, "", d); DECIDER = trim(d)
  next
}
file == "brief.md" && sect == "Kill criteria" && /^- \*\*KC-[^:*]*:\*\* / {
  k = $0; sub(/^- \*\*/, "", k); sub(/:\*\*.*$/, "", k)
  rest = $0; sub(/^- \*\*KC-[^:*]*:\*\*[ \t]*/, "", rest)
  if (rest ~ / — \*\*Superseded-by:\*\* /) next
  last = 0; off = 0; s = rest
  while ((i = index(s, " — by ")) > 0) { last = off + i; off += i; s = substr(s, i + 1) }
  if (last > 0) { d = trim(substr(rest, last + length(" — by "))); rest = substr(rest, 1, last - 1) }
  else d = trim(rest)
  KCN[++nk] = k; KCTEXT[k] = trim(rest); KCDATE[k] = d
  next

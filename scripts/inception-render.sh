#!/bin/sh
# inception-render.sh — the inception renderer: a venture bundle in, two
# self-contained HTML exports out (inception REQ-G1.1, REQ-G1.2, REQ-G1.3,
# REQ-C1.7 · D-9).
#
# Two modes, one per audience (REQ-G1.3):
#
#   dashboard  exports/venture.html. Opens with the status view REQ-G1.2 names
#              (gate readiness, blocking assumptions, kill criteria, open forks,
#              blockers), then the record behind it: opportunity, registers,
#              plan, discipline and stakeholder tables, sources, gate log. The
#              appetite and landscape prose is the pitch's.
#   pitch      exports/pitch.html. The narrative read for someone deciding
#              whether to back the venture: a one-paragraph status strip, then
#              problem, idea, metric, landscape, what has to be true, how it
#              will be tested, what would stop it, and the open questions.
#
# With no --mode both are rendered, which is what the scaffolded pre-commit
# step calls: every tracked export is regenerated by the commit that changes
# the bundle, so neither can lag it.
#
# What every page honors:
#   - Deterministic output. Same bundle, same bytes. There is no render
#     timestamp; "today" enters only through the kill-date classification and
#     is overridable (PLANWRIGHT_INCEPTION_TODAY) so a run that straddles
#     midnight is reproducible.
#   - Self-contained HTML. One file, inline style, no script, no network fetch.
#   - Escaped content. Bundle text is data, never markup: every value goes
#     through the shared escaper (scripts/html-escape.sh) before the two
#     inline forms this renders (code spans, bold) add their fixed tags.
#   - Version gating by DEFERRAL (REQ-C1.7): it calls the validator, which
#     owns the check, rather than re-implementing it. On an unsupported version
#     it refuses and leaves every existing export untouched, so a stale-but-valid
#     export is never replaced by a misparse.
#
# Publishing an export off this machine is a separate, always-offered step:
# scripts/inception-publish.sh.
#
# Usage:
#   inception-render.sh [--mode dashboard|pitch] [--output <file>] <venture-dir>
#
# --output names the destination of a single page, so it needs a --mode.
#
# Exit: 0 rendered · 2 usage or environment error · 3 the validator failed
#   closed and the bundle was not validated at all (a missing file, an
#   unbalanced fence, or an unsupported format-version — its refusal, passed
#   through unchanged).
#
# Environment:
#   PLANWRIGHT_INCEPTION_TODAY   YYYY-MM-DD; defaults to the system date.
#
# Portable POSIX sh + awk; bash 3.2 / BSD tooling floor (REQ-K1.5).
set -u

LC_ALL=C
export LC_ALL
unset CDPATH

script_dir=$(cd "$(dirname "$0")" && pwd) || exit 2

# The shared spec-parse grammar lib: the venture status declaration and the
# column-0 fence rule are the meta-spec's grammar, which the inception format
# inherits, so they come from the lib rather than from a private copy here (see
# the same note in inception-validate.sh). The escaper is shared with the other
# HTML renderers for the same reason. Both are sourced, never executed; fail
# closed when either is missing or unreadable.
for lib in spec-parse.sh html-escape.sh; do
  if [ ! -f "$script_dir/$lib" ] || [ ! -r "$script_dir/$lib" ]; then
    printf '%s\n' "inception-render: required helper $script_dir/$lib missing or not readable" >&2
    exit 2
  fi
done
# shellcheck source=scripts/spec-parse.sh
. "$script_dir/spec-parse.sh" || exit 2
# shellcheck source=scripts/html-escape.sh
. "$script_dir/html-escape.sh" || exit 2

usage() {
  echo "usage: inception-render.sh [--mode dashboard|pitch] [--output <file>] <venture-dir>" >&2
  exit 2
}

mode=
output=
target=
while [ $# -gt 0 ]; do
  case $1 in
    --mode)
      [ $# -ge 2 ] || usage
      mode=$2
      shift 2
      ;;
    --output)
      [ $# -ge 2 ] || usage
      output=$2
      shift 2
      ;;
    -*) usage ;;
    *)
      [ -z "$target" ] || usage
      target=$1
      shift
      ;;
  esac
done

case $mode in
  '' | dashboard | pitch) ;;
  *)
    echo "inception-render: --mode must be dashboard or pitch" >&2
    exit 2
    ;;
esac
if [ -n "$output" ] && [ -z "$mode" ]; then
  echo "inception-render: --output names one page, so it needs --mode dashboard or --mode pitch" >&2
  exit 2
fi

[ -n "$target" ] || usage
while [ "$target" != "${target%/}" ]; do target=${target%/}; done
[ -n "$target" ] || target=/
[ -d "$target" ] || {
  printf '%s\n' "inception-render: not a directory: $target" >&2
  exit 2
}
# awk reads an operand shaped name=value as a variable assignment, not a file,
# so a relative venture path such as `v=1` would render an empty page.
case $target in
  /*) ;;
  *) target="./$target" ;;
esac

# A bundle arrives through commits other people push. A symbolic link at
# exports/ would send the pages anywhere the link points, and one at a bundle
# file would pull content from outside the repo into a page that may be
# published, so neither is followed.
for entry in exports brief.md disciplines.md assumptions.md decisions.md plan.md; do
  if [ -h "$target/$entry" ]; then
    printf '%s\n' "inception-render: $entry is a symbolic link; refusing to render through it" >&2
    exit 2
  fi
done

# Readable, not executable, and run through /bin/sh: whatever copies a plugin
# tree onto a venture host may drop the +x bit without dropping the file, and
# refusing to render because of a file mode would take the export regeneration
# down with it. The validator declares #!/bin/sh, so this is what the kernel
# would have done with the bit set.
validator="$script_dir/inception-validate.sh"
[ -r "$validator" ] || {
  printf '%s\n' "inception-render: the validator is missing at $validator; refusing to render unchecked" >&2
  exit 2
}

# REQ-C1.7: the renderer refuses an unsupported version rather than parsing it,
# and defers to the validator's check instead of carrying its own copy.
vrc=0
/bin/sh "$validator" --version-check "$target" || vrc=$?
if [ "$vrc" -eq 3 ]; then
  # The validator fails closed for a missing file, an unbalanced fence, OR an
  # unsupported version, and hands all three back as exit 3. Point at its output
  # rather than naming one of the three: telling an operator their version is
  # unsupported when a file is simply absent sends them to the wrong line.
  echo "inception-render: refusing to render this bundle; the validator failed closed above and the exports are unchanged" >&2
  exit 3
elif [ "$vrc" -ne 0 ]; then
  exit 2
fi

today=${PLANWRIGHT_INCEPTION_TODAY:-$(date +%Y-%m-%d)}
case $today in
  [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
  *)
    echo "inception-render: PLANWRIGHT_INCEPTION_TODAY must be YYYY-MM-DD" >&2
    exit 2
    ;;
esac

# The status declaration comes from the lib and reaches awk through the
# environment, not through `-v`: awk expands backslash escapes in a `-v` value,
# and a bundle value is raw content that must reach the page verbatim.
INC_STATUS=$(spec_parse_header_value "$target/brief.md" Status 2>/dev/null) || INC_STATUS=
export INC_STATUS


function trim(s) { sub(/^[ \t]+/, "", s); sub(/[ \t]+$/, "", s); return s }

# Inline markdown, after escaping: `code` and **bold** gain their fixed tags
# around text esc() has already neutralized, so no bundle byte becomes markup.
function bold(s,   out) {
  out = ""
  while (match(s, /\*\*[^*]+\*\*/)) {
    out = out substr(s, 1, RSTART - 1) "<strong>" substr(s, RSTART + 2, RLENGTH - 4) "</strong>"
    s = substr(s, RSTART + RLENGTH)
  }
  return out s
}
# The match position is copied out before bold() runs: its own match() resets
# RSTART and RLENGTH, and a loop advancing on the clobbered values never ends.
function inl(s,   out, at, len) {
  s = esc(s); out = ""
  while (match(s, /`[^`]+`/)) {
    at = RSTART; len = RLENGTH
    out = out bold(substr(s, 1, at - 1)) "<code>" substr(s, at + 1, len - 2) "</code>"
    s = substr(s, at + len)
  }
  return out bold(s)
}

# The doctrine skip form, `_Skipped: <reason>._`: the reason, or "" when the
# text is not a skip.
function skipped(s) {
  if (s !~ /^_Skipped: .*_$/) return ""
  sub(/^_Skipped: /, "", s); sub(/_$/, "", s)
  return s
}

# A date that EXISTS, not merely one shaped like a date. days() below is happy
# to difference 2026-02-30 and hand back a state, and "tripped" is the state
# that tells a venture to kill or re-scope itself — so the calendar is checked
# here rather than trusted to have been checked upstream.
function date_ok(d,   y, m, dd, dim) {
  if (d !~ /^[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]$/) return 0
  y = substr(d, 1, 4) + 0; m = substr(d, 6, 2) + 0; dd = substr(d, 9, 2) + 0
  if (m < 1 || m > 12 || dd < 1) return 0
  dim = 31
  if (m == 4 || m == 6 || m == 9 || m == 11) dim = 30
  else if (m == 2) dim = ((y % 4 == 0 && y % 100 != 0) || y % 400 == 0) ? 29 : 28
  return (dd <= dim)
}

# Days since the civil epoch, so two ISO dates can be compared and differenced
# without a date(1) whose flags differ between GNU and BSD.
function days(d,   y, m, dd, era, yoe, doy, doe) {
  y = substr(d, 1, 4) + 0; m = substr(d, 6, 2) + 0; dd = substr(d, 9, 2) + 0
  y -= (m <= 2)
  era = int((y >= 0 ? y : y - 399) / 400)
  yoe = y - era * 400
  doy = int((153 * (m + (m > 2 ? -3 : 9)) + 2) / 5) + dd - 1
  doe = yoe * 365 + int(yoe / 4) - int(yoe / 100) + doy
  return era * 146097 + doe - 719468
}

function flush_field(   key) {
  if (kind == "" || fld == "") { fld = ""; return }
  key = kind SUBSEP id SUBSEP fld
  F[key] = val; SEEN[key] = 1
  fld = ""
}
function field(k, i, name) { return F[k SUBSEP i SUBSEP name] }
function live(k, i) { return !SEEN[k SUBSEP i SUBSEP "Superseded-by"] }

function isprose(s) {
  return s == "Success metric" || s == "Appetite" || s == "Existing alternatives" ||
    s == "Business viability" || s == "Strategy fit"
}

# A field value as HTML: its text, then any indented sub-bullets (an Options:
# list) as a list. Sub-bullets were joined with "\n" at parse time.
function value_html(v,   n, parts, i, out) {
  n = split(v, parts, "\n")
  out = inl(parts[1])
  if (n > 1) {
    out = out "<ul>"
    for (i = 2; i <= n; i++) out = out "<li>" inl(parts[i]) "</li>"
    out = out "</ul>"
  }
  return out
}
function dpair(label, v,   r) {
  if (v == "") return
  r = skipped(v)
  if (r != "") { print "<dt>" esc(label) "</dt><dd class=\"skip\">Skipped: " inl(r) "</dd>"; return }
  print "<dt>" esc(label) "</dt><dd>" value_html(v) "</dd>"
}
function dl(k, i, names,   n, nm, j) {
  n = split(names, nm, ",")
  print "<dl>"
  for (j = 1; j <= n; j++) dpair(nm[j], field(k, i, nm[j]))
  print "</dl>"
}
function paras(s,   n, p, i, r) {
  if (s == "") { print "<p class=\"skip\">Not written yet.</p>"; return }
  n = split(s, p, "\n")
  for (i = 1; i <= n; i++) {
    r = skipped(p[i])
    if (r != "") print "<p class=\"skip\">Skipped: " inl(r) "</p>"
    else print "<p>" inl(p[i]) "</p>"
  }
}
# An Opportunity field, which may carry the skip form as its value.
function opp(label, name, lead,   v, r) {
  v = field("OPP", "opp", name)
  if (v == "") return
  r = skipped(v)
  if (r != "") { print "<p class=\"skip\">" esc(label) " skipped: " inl(r) "</p>"; return }
  print "<p>" (lead ? "<strong>" esc(label) ":</strong> " : "") value_html(v) "</p>"
}
function table(s,   r, c, cell) {
  if (TR[s] == 0) return
  print "<h3>" esc(s) "</h3><table>"
  for (r = 1; r <= TR[s]; r++) {
    cell = (r == 1) ? "th" : "td"
    printf "<tr>"
    for (c = 1; c <= TC[s SUBSEP r]; c++)
      printf "<%s>%s</%s>", cell, inl(T[s SUBSEP r SUBSEP c]), cell
    print "</tr>"
  }
  print "</table>"
}
function kc_line(k) {
  if (KCSTATE[k] == "date unreadable")
    return "<li><span class=\"tag\">" esc(k) "</span> — date unreadable — " inl(KCTEXT[k]) "</li>"
  return "<li><span class=\"tag\">" esc(k) "</span> — " KCSTATE[k] \
    " — by " esc(KCDATE[k]) " — " inl(KCTEXT[k]) "</li>"
}
function kc_list(empty,   i) {
  if (DECIDER != "") print "<p>Gate decider: " esc(DECIDER) "</p>"
  print "<ul>"
  for (i = 1; i <= nk; i++) print kc_line(KCN[i])
  if (nk == 0) print "<li>" empty "</li>"
  print "</ul>"
}
# Date: is authoritative over the heading date (doctrine: Gate records).
function last_gate(   d) {
  if (ng == 0) return "No gate has run yet."
  d = G[ng SUBSEP "Date"]
  if (d == "") d = GHEADDATE[ng]
  return "Last gate: Gate " esc(GNUM[ng]) " — " esc(d) " — " esc(G[ng SUBSEP "Outcome"]) "."
}
# One register as H3 entries: live ones only, an empty message when none is.
function register(k, ids, n, names, empty,   i, j, id) {
  j = 0
  for (i = 1; i <= n; i++) {
    id = ids[i]
    if (!live(k, id)) continue
    j++
    print "<h3><span class=\"tag\">" esc(id) "</span> " inl(NAME[id]) "</h3>"
    dl(k, id, names)
  }
  if (j == 0) print "<p>" empty "</p>"
}


  h = $0; sub(/^### /, "", h); ng++; GHEAD[ng] = trim(h); gfld = ""
  GNUM[ng] = GHEAD[ng]; sub(/^Gate /, "", GNUM[ng]); sub(/ —.*$/, "", GNUM[ng])
